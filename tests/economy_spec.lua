local S,H,Q,F,A=E.Store,E.History,E.Query,E.Economy,E.API
local function eq(a,b,label)assert(a==b,(label or "Economy mismatch")..": "..tostring(a).." ~= "..tostring(b))end
local c=S.Character("economy-fixture",{name="Finance fixture"})
local lot1=F.Lot(c,100,{itemID=10,quantity=3,cost=101,evidence="observed purchase"},"lot1")
local lot2=F.Lot(c,110,{itemID=10,quantity=2,cost=120,evidence="observed purchase"},"lot2")
local sale=F.Sale(c,120,{itemID=10,quantity=4,gross=300,fees=10,evidence="completed sale"},"sale1")
local state=F.Replay(c,121)
eq(state.sales[sale.id].cost,161,"FIFO consumes the oldest lot first")
eq(state.inventoryKnownCost,60,"remaining portion retains its exact cost")
local report=F.Profit(c,115,121)
eq(report.profit,129,"costs acquired before the filter still count")
eq(report.gross,300); eq(report.cost,161); eq(report.fees,10)
eq(F.Lot(c,100,{itemID=10,quantity=3,cost=101,evidence="observed purchase"},"lot1").id,lot1.id,"observations deduplicate")
local ret=F.Return(c,130,{sale=sale.id,quantity=2,refund=150,feeRefund=2,evidence="observed refund"},"return1")
report=F.Profit(c,130,131); eq(report.cost,-67); eq(report.profit,-81,"refund is booked on return date")
state=F.Replay(c,131); eq(state.inventoryKnownCost,127,"return restores allocated costs")
local resale=F.Sale(c,140,{itemID=10,quantity=2,gross=160,fees=0,evidence="completed resale"},"resale")
eq(F.Replay(c,141).sales[resale.id].cost,67,"returned older acquisition is consumed before newer stock")
assert(not pcall(F.Return,c,150,{sale=sale.id,quantity=3,refund=1,feeRefund=0,evidence="invalid"},"too-many"))
local unknown=S.Character("economy-unknown",{name="Unknown cost fixture"})
F.Lot(unknown,100,{itemID=1,quantity=2},"unknown-old")
F.Lot(unknown,101,{itemID=1,quantity=2,cost=100,evidence="purchase"},"known-new")
local mixed=F.Sale(unknown,102,{itemID=1,quantity=3,gross=400,fees=0,evidence="sale"},"mixed")
local match=F.Replay(unknown,103).sales[mixed.id]
eq(match.unknownQuantity,2); eq(match.knownCost,50); eq(match.profit,nil,"unknown costs never become zero")
eq(F.Profit(unknown,0,103).profit,nil); eq(F.Profit(unknown,0,103).unmatched,1)
local missing=F.Sale(unknown,104,{itemID=2,quantity=1,gross=100,fees=0,evidence="sale"},"missing")
eq(F.Replay(unknown,105).sales[missing.id].shortfall,1)
F.Lot(unknown,106,{itemID=2,quantity=1,cost=25,evidence="later purchase"},"later")
eq(F.Replay(unknown,107).sales[missing.id].profit,nil,"future purchases cannot price past sales")
F.Lot(unknown,103,{itemID=2,quantity=1,cost=40,evidence="late-arriving earlier evidence"},"late")
eq(F.Replay(unknown,107).sales[missing.id].profit,60,"late evidence invalidates cached matching")
F.Reset(unknown,108,{itemID=2,quantity=2,evidence="inventory observed after gap"},"gap")
local afterGap=F.Sale(unknown,109,{itemID=2,quantity=1,gross=100,fees=0,evidence="sale"},"after-gap")
eq(F.Replay(unknown,110).sales[afterGap.id].profit,nil,"count snapshots do not manufacture acquisition costs")
local precision=S.Character("economy-copper",{name="Copper fixture"})
local ordering=S.Character("economy-opening-order",{name="Unknown age fixture"})
F.Lot(ordering,1,{itemID=1,quantity=2,cost=100,evidence="purchase"},"lot")
local oldSale=F.Sale(ordering,2,{itemID=1,quantity=1,gross=100,fees=0,evidence="sale"},"sale")
F.Reset(ordering,3,{itemID=1,quantity=1,evidence="count after gap"},"gap")
F.Return(ordering,4,{sale=oldSale.id,quantity=1,refund=100,feeRefund=0,evidence="return"},"return")
local uncertain=F.Sale(ordering,5,{itemID=1,quantity=1,gross=100,fees=0,evidence="sale after gap"},"uncertain")
eq(F.Replay(ordering,6).sales[uncertain.id].profit,nil,"unknown-age inventory cannot be skipped for a priced return")
F.Lot(precision,1,{itemID=3,quantity=3,cost=100,evidence="purchase"},"copper")
local sum=0
for i=1,3 do local r=F.Sale(precision,1+i,{itemID=3,quantity=1,gross=50,fees=0,evidence="sale"},"part"..i); sum=sum+F.Replay(precision,2+i).sales[r.id].cost end
eq(sum,100,"partial stacks conserve copper")
F.Lot(precision,10,{itemID=4,quantity=1,cost=0,evidence="explicit zero cash acquisition cost"},"free")
F.Sale(precision,11,{itemID=4,quantity=1,gross=0,fees=0,evidence="zero proceeds disposal sale"},"zero")
report=F.Profit(precision,10,12); eq(report.profit,0); eq(report.margin,nil); eq(report.roi,nil)
local wallet=S.Character("economy-wallet",{name="Wallet fixture"})
H.Wallet(wallet,1000,1000,"first"); H.Play(wallet,1000,false,"first")
H.Wallet(wallet,1005,1200,"first"); H.Play(wallet,1005,false,"first")
H.Wallet(wallet,1010,1100,"first"); H.Play(wallet,1010,false,"first")
H.Wallet(wallet,1015,1100,"first"); H.Play(wallet,1015,false,"first")
local proof=F.Evidence(wallet,1005,{amount=200,source="quest",session="first"},"reward")
local tx=Q.Kind(wallet,"gold")[1]
eq(tx.source,"quest"); eq(tx.quality,"inferred","wallet correlation is not confirmed attribution")
F.Evidence(wallet,1006,{amount=200,source="quest",session="first"},"competing")
eq(tx.source,"unknown","competing equal rewards undo an ambiguous inference")
local lootProof=F.Evidence(wallet,1005,{amount=200,source="loot",session="first"},"loot-proof")
F.Attribute(wallet,tx.id,"loot","confirmed",{lootProof.id})
assert(not F.Attribute(wallet,tx.id,"quest","inferred",{proof.id}),"confirmed classification cannot be downgraded automatically")
report=F.Report(wallet,1000,1015)
eq(report.wallet.complete,true); eq(report.wallet.opening,1000); eq(report.wallet.closing,1100)
eq(report.cashIn,200); eq(report.cashOut,100); eq(report.net,100); eq(report.operatingIn,200)
eq(report.netPerActiveHour,24000,"rates use fully observed active time")
eq(F.Report(wallet,1005,1010).wallet.opening,1000,"half-open boundary starts before same-second change")
eq(F.Report(wallet,1005,1010).wallet.closing,1200,"change at the end belongs to next period")
local baseline=H.Wallet(wallet,1100,5100,"second")
eq(baseline.kind,"balance"); eq(baseline.unobservedChange,4000)
report=F.Report(wallet,1000,1101); eq(report.net,100,"offline balance movement is not recorded income")
eq(report.wallet.complete,false); eq(report.wallet.closing,nil,"no invented end balance through a gap")
local points=report.wallet.points; local segments=0
for _,p in ipairs(points) do if p.breakBefore then segments=segments+1 end end
eq(segments,2,"graphs split at observation gaps")
local invalid=S.Character("economy-retention",{name="Missing flow fixture"})
H.Wallet(invalid,1,100,"a"); local removed=H.Wallet(invalid,5,200,"a"); H.Wallet(invalid,10,200,"a")
invalid.records[removed.id]=nil; E.Emit("RECORDS_REMOVED",invalid)
eq(F.WalletCoverage(invalid,1,10).complete,false,"retained balances cannot hide expired transaction details")
print("PASS economy: FIFO, partial stacks, dated returns, unknown costs, inventory boundaries, late evidence, source ambiguity, wallet gaps and rate coverage")
