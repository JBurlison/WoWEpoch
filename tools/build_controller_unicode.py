"""Build the controller editor's Unicode 17 data from pinned Unicode sources.

Normal invocation fetches missing source files into ignored .tools/unicode17 and
rebuilds the small runtime tables. --check never accesses the network: it checks
the published artifact digests, and also regenerates when all pinned sources are
cached. --download refreshes the cache, still rejecting every unexpected digest.
The engine and the generator are original My Epoch code; generated Unicode data
is redistributed under Unicode License V3 in MyEpoch/Licenses/Unicode.txt.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import hashlib
from io import BytesIO
import json
from pathlib import Path
import re
import unicodedata
from urllib.request import urlopen
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.tools/unicode17'
MANIFEST = ROOT / 'tools/controller-unicode-sources.json'
VERSION = '17.0.0'
BASE = f'https://www.unicode.org/Public/{VERSION}/ucd/'
SOURCES = {
    'Unihan.zip': (BASE + 'Unihan.zip', 'f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e'),
    'GraphemeBreakProperty.txt': (BASE + 'auxiliary/GraphemeBreakProperty.txt', 'd6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89'),
    'emoji-data.txt': (BASE + 'emoji/emoji-data.txt', '2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b'),
    'DerivedCoreProperties.txt': (BASE + 'DerivedCoreProperties.txt', '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08'),
    'GraphemeBreakTest.txt': (BASE + 'auxiliary/GraphemeBreakTest.txt', 'e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec'),
    'UnicodeLicense.txt': ('https://www.unicode.org/license.txt', 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96'),
}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_bytes(cache: Path = CACHE, download: bool = False) -> dict[str, bytes]:
    result = {}
    for name, (url, sha) in SOURCES.items():
        path = cache / name
        if download or not path.is_file():
            data = urlopen(url, timeout=60).read()
            if digest(data) != sha:
                raise ValueError(f'Unicode source digest mismatch: {name}')
            cache.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if digest(data) != sha:
            raise ValueError(f'Unicode source digest mismatch: {name}')
        result[name] = data
    return result


def merged_ranges(rows: list[tuple[int, int]]) -> list[int]:
    merged: list[list[int]] = []
    for first, last in sorted(rows):
        if merged and first <= merged[-1][1] + 1:
            merged[-1][1] = max(last, merged[-1][1])
        else:
            merged.append([first, last])
    return [item for pair in merged for item in pair]


def properties(data: bytes, wanted: str | None = None) -> dict[str, list[int]]:
    result: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for line in data.decode('utf-8').splitlines():
        text = line.split('#', 1)[0].strip()
        if not text:
            continue
        parts = [part.strip() for part in text.split(';')]
        if wanted and (len(parts) < 3 or parts[1] != wanted):
            continue
        name = parts[2] if wanted else parts[1]
        limits = parts[0].split('..')
        first, last = int(limits[0], 16), int(limits[-1], 16)
        result[name].append((first, last))
    return {name: merged_ranges(rows) for name, rows in sorted(result.items())}


def range_lua(values: list[int]) -> str:
    chunks = [','.join(f'0x{value:X}' for value in values[i:i + 20]) for i in range(0, len(values), 20)]
    return '{\n    ' + ',\n    '.join(chunks) + '\n  }'


def unicode_table(sources: dict[str, bytes]) -> str:
    gcb = properties(sources['GraphemeBreakProperty.txt'])
    incb = properties(sources['DerivedCoreProperties.txt'], 'InCB')
    emoji = properties(sources['emoji-data.txt'])['Extended_Pictographic']
    result = [
        '-- Generated by tools/build_controller_unicode.py; do not edit.',
        '-- Unicode 17.0.0 / UAX #29. Unicode License V3: Licenses/Unicode.txt.',
        'local _,E=...',
        "E.ControllerUnicodeData={version='17.0.0',gcb={",
    ]
    for name, ranges in gcb.items():
        result.append(f'  {name}={range_lua(ranges)},')
    result.append('},extendedPictographic=' + range_lua(emoji) + ',incb={')
    for name, ranges in incb.items():
        result.append(f'  {name}={range_lua(ranges)},')
    result.append('}}')
    return '\n'.join(result) + '\n'


TONE_MARKS = {'\u0304': '1', '\u0301': '2', '\u030c': '3', '\u0300': '4'}


def pinyin_key(value: str) -> str:
    """Convert Unihan's diacritics into an ASCII syllable plus tone (neutral 5)."""
    tone = '5'
    chars: list[str] = []
    for ch in unicodedata.normalize('NFD', value.lower().strip()):
        if ch in TONE_MARKS:
            tone = TONE_MARKS[ch]
        elif ch == '\u0308' and chars and chars[-1] == 'u':
            chars[-1] = 'v'
        elif unicodedata.category(ch) == 'Mn':
            # Rare ê variants are searchable under e; no stored writing is normalized.
            continue
        elif ch in '12345':
            tone = ch
        else:
            chars.append(ch)
    syllable = ''.join(chars)
    if not re.fullmatch('[a-zv]+', syllable):
        raise ValueError(f'Unexpected Unihan Pinyin spelling: {value!r}')
    return syllable + tone


def unihan_rows(sources: dict[str, bytes]):
    with ZipFile(BytesIO(sources['Unihan.zip'])) as archive:
        for name in ('Unihan_Readings.txt', 'Unihan_Variants.txt', 'Unihan_DictionaryLikeData.txt'):
            for line in archive.read(name).decode('utf-8').splitlines():
                if line and not line.startswith('#'):
                    code, field, value = line.split('\t', 2)
                    yield int(code[2:], 16), field, value


def chinese_index(sources: dict[str, bytes]) -> tuple[dict[str, str], str, str, dict[str, int]]:
    readings: dict[int, set[str]] = defaultdict(set)
    counts: dict[tuple[int, str], int] = defaultdict(int)
    variants: dict[int, set[int]] = defaultdict(set)
    scripts: dict[str, set[int]] = {'simplified': set(), 'traditional': set()}
    grade: dict[int, int] = {}
    core: dict[int, str] = {}
    for cp, field, value in unihan_rows(sources):
        values = []
        if field == 'kMandarin':
            values = value.split()
        elif field in ('kHanyuPinyin', 'kXHC1983'):
            values = [reading for entry in value.split() for reading in entry.rsplit(':', 1)[-1].split(',')]
        elif field == 'kHanyuPinlu':
            for reading, count in re.findall(r'([^\s()]+)\((\d+)\)', value):
                key = pinyin_key(reading)
                readings[cp].add(key)
                counts[cp, key] = max(counts[cp, key], int(count))
        elif field in ('kSimplifiedVariant', 'kTraditionalVariant'):
            targets = {int(code, 16) for code in re.findall(r'U\+([0-9A-F]+)', value)} - {cp}
            variants[cp].update(targets)
            for target in targets:
                variants[target].add(cp)
            if targets:
                source_kind, target_kind = ('traditional', 'simplified') if field == 'kSimplifiedVariant' else ('simplified', 'traditional')
                scripts[source_kind].add(cp)
                scripts[target_kind].update(targets)
        elif field == 'kGradeLevel':
            grade[cp] = int(value)
        elif field == 'kUnihanCore2020':
            core[cp] = value
        for reading in values:
            readings[cp].add(pinyin_key(reading))

    # Variant preference affects the list order, never conversion of entered text.
    # Transfer frequency evidence only where the corresponding reading agrees.
    original_counts = dict(counts)
    for cp, alternatives in variants.items():
        for other in alternatives:
            for key in readings.get(cp, set()) & readings.get(other, set()):
                counts[cp, key] = max(counts[cp, key], original_counts.get((other, key), 0))
    query_chars: dict[str, set[int]] = defaultdict(set)
    for cp, keys in readings.items():
        for key in keys:
            query_chars[key].add(cp)
            query_chars[key[:-1]].add(cp)

    def order(cp: int, key: str) -> tuple[int, int, int, int]:
        frequency = counts.get((cp, key), 0) if key[-1].isdigit() else sum(counts.get((cp, spelling), 0) for spelling in readings[cp] if spelling[:-1] == key)
        alternatives = variants.get(cp, set()) | {cp}
        level = min((grade.get(other, 99) for other in alternatives), default=99)
        common = any(core.get(other) for other in alternatives)
        return -frequency, level, 0 if common else 1, cp

    packed = {key: ''.join(chr(cp) for cp in sorted(values, key=lambda cp: order(cp, key))) for key, values in sorted(query_chars.items())}
    simplified = ''.join(chr(cp) for cp in sorted(scripts['simplified'] - scripts['traditional']))
    traditional = ''.join(chr(cp) for cp in sorted(scripts['traditional'] - scripts['simplified']))
    stats = {'characters': len(readings), 'tone_reading_pairs': sum(map(len, readings.values())),
             'query_keys': len(packed), 'tone_keys': sum(key[-1].isdigit() for key in packed)}
    return packed, simplified, traditional, stats


def chinese_table(sources: dict[str, bytes]) -> tuple[str, dict[str, int]]:
    readings, simplified, traditional, stats = chinese_index(sources)
    result = [
        '-- Generated by tools/build_controller_unicode.py; do not edit.',
        '-- Unihan 17.0.0. Unicode License V3: Licenses/Unicode.txt.',
        '-- Candidate strings are decoded only for the active syllable by ControllerComposition.',
        'local _,E=...',
        "E.ControllerChinese={version='17.0.0',readings={",
    ]
    for key, chars in readings.items():
        result.append(f'  ["{key}"]="{chars}",')
    result += ['},', f'simplified="{simplified}",', f'traditional="{traditional}"', '}']
    return '\n'.join(result) + '\n', stats


def generate(sources: dict[str, bytes]) -> tuple[dict[str, bytes], dict[str, int]]:
    chinese, stats = chinese_table(sources)
    outputs = {
        'MyEpoch/ControllerChinese.lua': chinese.encode('utf-8'),
        'MyEpoch/ControllerUnicodeData.lua': unicode_table(sources).encode('utf-8'),
        'MyEpoch/Licenses/Unicode.txt': sources['UnicodeLicense.txt'],
    }
    return outputs, stats


def artifact_manifest(sources: dict[str, bytes], outputs: dict[str, bytes], stats: dict[str, int]) -> dict:
    return {
        'unicode_version': VERSION,
        'generator': 'tools/build_controller_unicode.py',
        'sources': {name: {'url': url, 'sha256': sha, 'bytes': len(sources[name])} for name, (url, sha) in SOURCES.items()},
        'outputs': {name: {'sha256': digest(data), 'bytes': len(data)} for name, data in outputs.items()},
        'chinese': stats,
    }


def check(root: Path = ROOT, cache: Path = CACHE) -> dict:
    manifest = json.loads((root / 'tools/controller-unicode-sources.json').read_text(encoding='utf-8'))
    if manifest['unicode_version'] != VERSION or set(manifest['sources']) != set(SOURCES):
        raise ValueError('Controller Unicode manifest source/version mismatch.')
    for name, (url, sha) in SOURCES.items():
        if manifest['sources'][name]['url'] != url or manifest['sources'][name]['sha256'] != sha:
            raise ValueError(f'Controller Unicode source pin mismatch: {name}')
    for name, meta in manifest['outputs'].items():
        data = (root / name).read_bytes()
        if len(data) != meta['bytes'] or digest(data) != meta['sha256']:
            raise ValueError(f'Generated controller Unicode data is stale: {name}')
    if all((cache / name).is_file() for name in SOURCES):
        sources = source_bytes(cache)
        outputs, stats = generate(sources)
        if manifest != artifact_manifest(sources, outputs, stats):
            raise ValueError('Controller Unicode generator output differs from manifest.')
        for name, data in outputs.items():
            if (root / name).read_bytes() != data:
                raise ValueError(f'Generated controller Unicode data differs: {name}')
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated artifacts offline; regenerate too if sources are cached.')
    parser.add_argument('--download', action='store_true', help='Fetch and verify all source pins before generating.')
    args = parser.parse_args()
    if args.check:
        if args.download:
            parser.error('--check is offline and cannot be combined with --download')
        manifest = check()
        print('Controller Unicode data verified:', manifest['chinese'])
        return
    sources = source_bytes(download=args.download)
    outputs, stats = generate(sources)
    for name, data in outputs.items():
        path = ROOT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    MANIFEST.write_text(json.dumps(artifact_manifest(sources, outputs, stats), indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print('Generated controller Unicode data:', stats)


if __name__ == '__main__':
    main()
